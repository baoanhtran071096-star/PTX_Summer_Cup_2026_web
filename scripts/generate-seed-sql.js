#!/usr/bin/env node
// ============================================================
// Generates supabase/seed.sql from docs/migration/r25-extracted.json
// (produced by scripts/extract-r25-data.js). Programmatic generation
// avoids hand-transcribing 24 players/3 teams/3 matches and risking
// silent transcription errors during the M01 migration.
//
// Usage: node scripts/generate-seed-sql.js
// (re-run scripts/extract-r25-data.js first if the legacy source changed)
// ============================================================

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const EXTRACTED_PATH = path.join(ROOT, 'docs', 'migration', 'r25-extracted.json');
const OUT_PATH = path.join(ROOT, 'supabase', 'seed.sql');

function sqlString(value) {
    if (value === null || value === undefined) return 'null';
    return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlJson(value) {
    return `'${JSON.stringify(value).replace(/'/g, "''")}'::jsonb`;
}

function main() {
    const data = JSON.parse(fs.readFileSync(EXTRACTED_PATH, 'utf8'));

    const lines = [];
    lines.push('-- ============================================================');
    lines.push('-- Generated by scripts/generate-seed-sql.js from docs/migration/r25-extracted.json');
    lines.push('-- DO NOT hand-edit — re-run the generator instead, so the seed');
    lines.push('-- always matches the frozen M-02 extraction manifest.');
    lines.push('--');
    lines.push('-- Known open item applied here: PLAYERS_DATA legacy_id 18 is');
    lines.push('-- seeded with its live index.html display name ("Xuân Sử") —');
    lines.push('-- see r25-data-reconciliation-plan.md §2 for the unresolved');
    lines.push('-- name/asset-filename mismatch that must be confirmed with the');
    lines.push('-- product owner before Release Candidate.');
    lines.push('--');
    lines.push('-- logo_path / avatar_path are left NULL here on purpose: they must');
    lines.push('-- hold a real Supabase Storage object key, which does not exist');
    lines.push('-- until M09 runs the actual upload against docs/migration/');
    lines.push('-- r25-asset-manifest.json. Seeding a raw legacy relative path into');
    lines.push('-- these columns would be an invalid/dangling reference.');
    lines.push('-- ============================================================');
    lines.push('');

    lines.push('-- Teams');
    for (const t of data.teams) {
        lines.push(
            `insert into public.teams (id, name, full_name, icon, color, captain_name, stats, ovr, logo_path) values (` +
            `${sqlString(t.legacy_id)}, ${sqlString(t.name)}, ${sqlString(t.full_name)}, ${sqlString(t.icon)}, ` +
            `${sqlString(t.color)}, ${sqlString(t.captain_name)}, ${sqlJson(t.stats)}, ${t.ovr}, null);`
        );
    }
    lines.push('');

    lines.push('-- Players');
    for (const p of data.players) {
        lines.push(
            `insert into public.players (legacy_id, name, team_id, position, avatar_path) values (` +
            `${p.legacy_id}, ${sqlString(p.name)}, ${sqlString(p.team_legacy_id)}, ${sqlString(p.position)}, null);`
        );
    }
    lines.push('');

    lines.push('-- Matches');
    for (const m of data.matches) {
        lines.push(
            `insert into public.matches (legacy_id, home_team_id, away_team_id, match_date, start_time, end_time) values (` +
            `${m.legacy_id}, ${sqlString(m.home_team_legacy_id)}, ${sqlString(m.away_team_legacy_id)}, ` +
            `${sqlString(m.match_date)}, ${sqlString(m.start_time)}, ${sqlString(m.end_time)});`
        );
    }
    lines.push('');

    lines.push('-- Tournament settings');
    const s = data.tournamentSettings;
    lines.push(
        `update public.tournament_settings set slogan = ${sqlString(s.slogan)}, message = ${sqlString(s.message)}, ` +
        `event_date = ${sqlString(s.event_date)}, location = ${sqlString(s.location)} where id = true;`
    );
    lines.push('');

    if (data.hallOfFame.length) {
        const teamsByLabel = new Map(data.teams.map((t) => [`${t.name} (${t.full_name})`, t.legacy_id]));
        const resolveTeam = (label) => {
            if (!label) return { id: null, warning: null };
            const id = teamsByLabel.get(label);
            return id ? { id, warning: null } : { id: null, warning: `unresolved team label "${label}"` };
        };

        lines.push('-- Hall of Fame');
        lines.push('-- champion/runner_up/third_place resolved from legacy free-text');
        lines.push('-- "TEAM X (FULLNAME)" labels against the teams seeded above.');
        lines.push('-- golden_boot/mvp are player NAMES, not yet resolved to players.id');
        lines.push('-- (legacy export has no player-id reference for these, only a');
        lines.push('-- display name) — left NULL with the name recorded in a comment');
        lines.push('-- for manual admin-panel assignment once M04/M11 exist.');
        for (const h of data.hallOfFame) {
            const champion = resolveTeam(h.champion);
            const runnerUp = resolveTeam(h.runner_up);
            const thirdPlace = resolveTeam(h.third_place);
            for (const w of [champion.warning, runnerUp.warning, thirdPlace.warning].filter(Boolean)) {
                lines.push(`-- WARNING (year ${h.year}): ${w}`);
            }
            if (h.golden_boot) lines.push(`-- year ${h.year} golden_boot player name (unresolved): ${h.golden_boot}`);
            if (h.mvp) lines.push(`-- year ${h.year} mvp player name (unresolved): ${h.mvp}`);
            lines.push(
                `insert into public.hall_of_fame (year, champion_team_id, runner_up_team_id, third_place_team_id) values (` +
                `${h.year}, ${sqlString(champion.id)}, ${sqlString(runnerUp.id)}, ${sqlString(thirdPlace.id)}) ` +
                `on conflict (year) do update set champion_team_id = excluded.champion_team_id, ` +
                `runner_up_team_id = excluded.runner_up_team_id, third_place_team_id = excluded.third_place_team_id;`
            );
        }
    }

    fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
    fs.writeFileSync(OUT_PATH, lines.join('\n') + '\n', 'utf8');
    console.log(`Wrote ${path.relative(ROOT, OUT_PATH)} (${data.teams.length} teams, ${data.players.length} players, ${data.matches.length} matches)`);
}

main();
